#!/usr/bin/env node
/* eslint-env node */
/**
 * Writes the adaptive launcher icon (Android 8+) as vector drawables: a fan of four TAKI cards,
 * one per colour, on the blue table. The legacy PNGs for Android 7 are rendered from the same
 * design by scripts/render-icon-pngs.ps1.
 *
 *   node scripts/generate-icon.js
 */
const fs = require('fs');
const path = require('path');

const RES = path.join(__dirname, '..', 'android', 'app', 'src', 'main', 'res');

// Shared design (also mirrored in render-icon-pngs.ps1). Units: the 108-dp adaptive canvas.
const DESIGN = {
  background: '#1E63AD',
  glow: '#2EFFFFFF',
  cardWidth: 26,
  cardHeight: 36,
  cardRadius: 3.5,
  cardTop: 36,
  pivotY: 86,
  fan: [
    { rotation: -24, color: '#E63946' },
    { rotation: -8, color: '#2A7DE1' },
    { rotation: 8, color: '#2BB673' },
    { rotation: 24, color: '#F5C518' },
  ],
};

function roundedRect(x, y, w, h, r) {
  return [
    `M${x + r},${y}`,
    `H${x + w - r}`,
    `A${r},${r} 0 0 1 ${x + w},${y + r}`,
    `V${y + h - r}`,
    `A${r},${r} 0 0 1 ${x + w - r},${y + h}`,
    `H${x + r}`,
    `A${r},${r} 0 0 1 ${x},${y + h - r}`,
    `V${y + r}`,
    `A${r},${r} 0 0 1 ${x + r},${y}`,
    'Z',
  ].join(' ');
}

function circle(cx, cy, r) {
  return `M${cx - r},${cy} A${r},${r} 0 1 0 ${cx + r},${cy} A${r},${r} 0 1 0 ${cx - r},${cy} Z`;
}

function card(color) {
  const { cardWidth: w, cardHeight: h, cardRadius: r, cardTop: y } = DESIGN;
  const x = 54 - w / 2;
  const cx = 54;
  const cy = y + h / 2;
  return [
    `    <path android:fillColor="#55000000" android:pathData="${roundedRect(x + 1.2, y + 1.8, w, h, r)}"/>`,
    `    <path android:fillColor="#FFFFFFFF" android:pathData="${roundedRect(x, y, w, h, r)}"/>`,
    `    <path android:fillColor="#FFE4EAF3" android:pathData="${roundedRect(x, y, w, h, r)}" android:strokeWidth="1.2" android:strokeColor="#FFE4EAF3" android:fillAlpha="0"/>`,
    `    <path android:fillColor="${color}" android:pathData="${circle(cx, cy, 7.5)}"/>`,
    `    <path android:fillColor="#66FFFFFF" android:pathData="${circle(cx - 2.5, cy - 3, 2.2)}"/>`,
    `    <path android:fillColor="${color}" android:pathData="${roundedRect(x + 2.5, y + 2.5, 4, 5.5, 1.1)}"/>`,
    `    <path android:fillColor="${color}" android:pathData="${roundedRect(x + w - 6.5, y + h - 8, 4, 5.5, 1.1)}"/>`,
  ].join('\n');
}

const foreground = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-icon.js: a fan of TAKI cards on the table. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="${DESIGN.glow}" android:pathData="${circle(54, 54, 34)}"/>
${DESIGN.fan
  .map(
    f => `    <group android:rotation="${f.rotation}" android:pivotX="54" android:pivotY="${DESIGN.pivotY}">
${card(f.color)}
    </group>`,
  )
  .join('\n')}
</vector>
`;

const background = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-icon.js -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="${DESIGN.background}" android:pathData="M0,0h108v108h-108z"/>
    <path android:fillColor="#14000000" android:pathData="M0,0h108v108h-108z M54,54 m-62,0 a62,62 0 1 0 124,0 a62,62 0 1 0 -124,0z" android:fillType="evenOdd"/>
</vector>
`;

const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
`;

// Themed-icon variant (Android 13+): the card fan as a single-colour silhouette.
const monochrome = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-icon.js -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
${DESIGN.fan
  .map(f => {
    const { cardWidth: w, cardHeight: h, cardRadius: r, cardTop: y } = DESIGN;
    const x = 54 - w / 2;
    return `    <group android:rotation="${f.rotation}" android:pivotX="54" android:pivotY="${DESIGN.pivotY}">
        <path android:fillColor="#FFFFFFFF" android:pathData="${roundedRect(x, y, w, h, r)}"/>
        <path android:fillColor="#FF000000" android:pathData="${roundedRect(x + 1.5, y + 1.5, w - 3, h - 3, r - 1)}"/>
        <path android:fillColor="#FFFFFFFF" android:pathData="${circle(54, y + h / 2, 7.5)}"/>
    </group>`;
  })
  .join('\n')}
</vector>
`;

const files = {
  'drawable/ic_launcher_foreground.xml': foreground,
  'drawable/ic_launcher_background.xml': background,
  'drawable/ic_launcher_monochrome.xml': monochrome,
  'mipmap-anydpi-v26/ic_launcher.xml': adaptive,
  'mipmap-anydpi-v26/ic_launcher_round.xml': adaptive,
};

for (const [rel, content] of Object.entries(files)) {
  const file = path.join(RES, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  console.log('wrote', rel);
}
